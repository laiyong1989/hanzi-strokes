def read_js(path, anchor):
    raw = open(path, encoding='utf-8').read()
    i = raw.index(anchor)
    j = raw.index('{', i)
    return raw[:j], json.loads(raw[j:].rstrip().rstrip(';'))


def main():
    dry = '--dry' in sys.argv
    head, D = read_js(DICT_JS, 'window.HZ_DICT=')
    assert head.rstrip().endswith('window.HZ_DICT='), '文件头异常，已放弃'

    # 1) 教材注音（带组词语境）
    praw = os.path.join(ROOT, '.build/pinyin_raw.json')
    textbook = {}
    if os.path.exists(praw):
        textbook = json.load(open(praw, encoding='utf-8'))
    n_tb = 0
    for ch, items in textbook.items():
        if ch not in D:
            continue
        pw = dict(D[ch].get('pw') or {})
        for it in items:
            for w in it['w']:
                if pw.get(w) != it['py']:
                    pw[w] = it['py']
                    n_tb += 1
        if pw:
            D[ch]['pw'] = pw

    # 2) 人工校对表（优先级最高）
    n_m = 0
    for ch, spec in MULTI.items():
        if ch not in D:
            continue
        p = list(spec['p'])
        for old in (D[ch].get('p') or []):
            if old not in p:
                p.append(old)
        D[ch]['p'] = p
        pw = dict(spec['pw'])
        for w, v in (D[ch].get('pw') or {}).items():
            pw.setdefault(w, v)
        D[ch]['pw'] = pw
        n_m += 1

    if dry:
        for ch in ['处', '长', '地', '乐', '着', '干', '脏', '调', '似', '尽']:
            if ch in D:
                print('%s p=%s pw=%s' % (ch, D[ch]['p'], D[ch].get('pw')))
        print('\n教材注音写入 %d 条词音；人工表覆盖 %d 个字' % (n_tb, n_m))
        return

    shutil.copyfile(DICT_JS, os.path.join(ROOT, '.build/dict.js.bak3'))
    open(DICT_JS, 'w', encoding='utf-8').write(
        head + json.dumps(D, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('教材注音写入 %d 条词音；人工表覆盖 %d 个字' % (n_tb, n_m))
    print('已写入 data/dict.js（备份 .build/dict.js.bak3）')


if __name__ == '__main__':
    main()
